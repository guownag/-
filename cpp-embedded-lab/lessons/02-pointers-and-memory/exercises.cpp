// ===========================================================================
// 第 1 题 · reverse_in_place —— 就地把数组倒过来
// ===========================================================================
//
// 【含义】
//   data 指向 n 个 int32_t 的连续内存。把它们的顺序反过来，
//   而且**不许申请新内存**，只能在原地交换。
//
//     {1, 2, 3, 4, 5}  ->  {5, 4, 3, 2, 1}
//     {10, 20}         ->  {20, 10}
//     {7}              ->  {7}            （一个元素不用动）
//
// 【场景】
//   听起来像个算法练习题，但嵌入式里真用得上：
//   * 有些通信协议要求大端字节序，而你收到的是小端的一个字节数组，
//     需要在原地把字节顺序翻过来再解析。
//   * LCD 屏的扫描顺序和显存顺序相反时，整块缓冲区要翻转。
//
//   这就是所谓的**双指针**（或者叫"头尾夹逼"）套路，
//   后面写查找、分区、环形缓冲都会反复用到。
//
// 【思路】
//   两个下标：i 从 0 往前走，j 从 n-1 往后走。
//   交换 data[i] 和 data[j]，然后 i 加一、j 减一，直到 i 不小于 j 为止。
//
//   循环退出有两种方式，取决于元素个数：
//
//     奇数个 (n = 5)：{1,2,3,4,5}
//       i=0,j=4 交换 -> i=1,j=3 交换 -> i=2,j=2，i==j，停止
//       中间那个元素 data[2] 从来没被碰过 —— 它本来就该待在原地
//
//     偶数个 (n = 4)：{1,2,3,4}
//       i=0,j=3 交换 -> i=1,j=2 交换 -> i=2,j=1，i>j，停止
//       i 和 j 交错而过，谁也不剩
//
//   所以终止条件是"i < j 不成立"，它同时覆盖了 i==j 和 i>j 两种情况。
//
//   写成 while (i <= j) 也不会算错，只是奇数个元素时会多做一次
//   data[i] 和它自己的交换 —— 没意义，但也不会有害。用 < 语义更准：
//   "两个人还没相遇就继续走"。
//
// 【陷阱】
//   1. std::size_t 是**无符号**类型。千万别写
//        for (size_t j = n - 1; j >= 0; --j)
//      因为 j >= 0 对无符号数永远成立，j 减到 0 之后会回绕成
//      一个巨大的数，循环永远不会结束。这是 C/C++ 最经典的死循环。
//      用 while (i < j) 这种形式天然避开它。
//
//   2. 交换三个步骤别写反，否则两个元素会变成一样的值。
//      有现成的 std::swap，但这一课请手写，体会一下临时变量的作用。
//
//   3. n == 0 时 data 可能是 nullptr。函数一开头就要挡掉，
//      否则 n - 1 会算出天文数字，然后解引用野指针。
//
// 【写完自检】
//   测试覆盖奇数个元素、偶数个元素、1 个元素、0 个元素、负数。
//   注意其中一条是 reverse_in_place(nullptr, 0)，它必须安全返回。
//
// ===========================================================================
void reverse_in_place(std::int32_t* data, std::size_t n) {
    if(data==nullptr || n==0)
    {
        return;
    }

    std::int32_t temp;
    std::size_t a = n - 1;
    std::size_t b = 0;
    while(a>b){
        temp=data[a];
        data[a]=data[b];
        data[b]=temp;
        a-=1;
        b+=1;

    }
}

// ===========================================================================
// 第 2 题 · read_u32_le / read_u32_be / write_u32_le / write_u32_be
//            —— 端序（字节序）读写
// ===========================================================================
//
// 【含义】
//   一个 32 位整数 0x12345678 在内存里占 4 个字节，但**哪个字节在前**
//   是有两种约定的：
//
//     小端 (LE)：低字节在前   78 56 34 12     x86、ARM Cortex-M 默认
//     大端 (BE)：高字节在前   12 34 56 78     网络字节序、很多工业协议
//
//   read_u32_le(p) 从 p 处读 4 个字节，按小端解释成一个 32 位整数。
//   read_u32_be(p) 同上，按大端解释。
//   write_u32_le / write_u32_be 是反方向：把一个整数按指定端序写出去。
//
// 【场景】
//   只要你的设备和别的设备通信，就一定会遇到这个。
//   协议文档上写的"该字段为 32 位无符号整数，大端序"是硬性规定，
//   跟你的 CPU 是什么端序毫无关系。
//
//   为什么不能用 memcpy 或者 reinterpret_cast 直接读？
//   因为那样得到的结果**取决于你的 CPU**。在 Cortex-M（小端）上跑得好好的
//   代码，换到某些大端 DSP 上就全错，而且错得很隐蔽 —— 数值整体字节颠倒。
//
//   所以协议解析必须显式地逐字节拼装，把端序写死在代码里。
//
// 【思路】小端就是"低字节在低地址"
//   p[0] 是最低 8 位，p[1] 是次低 8 位，依此类推：
//
//     read_u32_le = p[0] | (p[1] << 8) | (p[2] << 16) | (p[3] << 24)
//
//   大端正好反过来：
//
//     read_u32_be = (p[0] << 24) | (p[1] << 16) | (p[2] << 8) | p[3]
//
//   写就是反过来：把 v 的不同 8 位分别取出来放到对应位置。
//   取最低 8 位：v & 0xFF；取次低 8 位：(v >> 8) & 0xFF；依此类推。
//
// 【陷阱】每个字节都必须先转成 uint32_t
//   p 是 uint8_t*，p[0] 是 uint8_t。写 p[0] << 24 时，
//   C++ 会先把它**整型提升**成 int（32 位有符号），再做移位。
//   当 p[0] >= 128 时，int 左移 24 位会超过 INT32_MAX，是**未定义行为**。
//
//     错误：  p[0] << 24
//     正确：  static_cast<std::uint32_t>(p[0]) << 24
//
//   测试里有一条 read_u32_le 读 0x12345678，其中最高字节 0x12 不触发问题；
//   但 read_u32_be 读同一个数时 p[0] 就是 0x12 左移 24 位 —— 更别提前面
//   还有 0xDEADBEEF 这种测试数据。所以每个字节都要转。
//
//   第二个好处：显式转换的写法**不要求 p 是对齐的**。
//   你只对单个字节做访问，永远不会触发 Cortex-M0 上的非对齐访问异常。
//   测试专门用 p+1、p+3 这种错位地址验过。
//
// 【写完自检】
//   测试会写进去再读出来，检查能不能还原；还会故意用非对齐地址。
//
// ===========================================================================
std::uint32_t read_u32_le(const std::uint8_t* p) {
    return static_cast<std::uint32_t>(p[0]) |
           (static_cast<std::uint32_t>(p[1]) << 8) |
           (static_cast<std::uint32_t>(p[2]) << 16) |
           (static_cast<std::uint32_t>(p[3]) << 24);
}

std::uint32_t read_u32_be(const std::uint8_t* p) {
    return (static_cast<std::uint32_t>(p[0]) << 24) |
           (static_cast<std::uint32_t>(p[1]) << 16) |
           (static_cast<std::uint32_t>(p[2]) << 8) |
           static_cast<std::uint32_t>(p[3]);
}

void write_u32_le(std::uint8_t* p, std::uint32_t v) {
    p[0] = static_cast<std::uint8_t>(v & 0xFFu);
    p[1] = static_cast<std::uint8_t>((v >> 8) & 0xFFu);
    p[2] = static_cast<std::uint8_t>((v >> 16) & 0xFFu);
    p[3] = static_cast<std::uint8_t>((v >> 24) & 0xFFu);
}

void write_u32_be(std::uint8_t* p, std::uint32_t v) {
    p[0] = static_cast<std::uint8_t>((v >> 24) & 0xFFu);
    p[1] = static_cast<std::uint8_t>((v >> 16) & 0xFFu);
    p[2] = static_cast<std::uint8_t>((v >> 8) & 0xFFu);
    p[3] = static_cast<std::uint8_t>(v & 0xFFu);
}

// ===========================================================================
// 第 3 题 · is_little_endian —— 运行时判断当前平台的端序
// ===========================================================================
//
// 【含义】
//   返回 true 表示当前 CPU 是小端。x86 和 ARM Cortex-M 默认都是小端，
//   所以在你手上的机器上它应该返回 true。
//
// 【场景】
//   为什么需要一个运行时函数，而不是编译期常量？
//   因为你的代码可能同时跑在主机（PC，小端）和目标板上。
//   写协议测试的时候，先问一句"我现在在什么端序的机器上"，
//   就能构造出正确的测试数据。
//
//   有些项目还会在启动时做一次自检：如果不满足假设就直接进错误处理，
//   而不是带着错误的假设继续跑。
//
// 【思路】
//   准备一个值已知的多字节变量，然后**只看它的第一个字节**。
//
//     uint16_t probe = 1;              // 内存里是 00 01 或 01 00
//     取 probe 的地址，转成 uint8_t*
//     看第一个字节是不是 1
//
//   如果是 1，说明最低有效字节排在最前面，这就是小端。
//   如果是 0，说明最高有效字节排在最前面，这就是大端。
//
// 【陷阱】
//   1. 类型转换要用 reinterpret_cast，不要用 C 风格的 (uint8_t*)&probe。
//      C++ 里 reinterpret_cast 一眼就能看出"这里在做危险的重新解释"，
//      搜索代码时也好找。
//
//   2. 别用 union 搞类型双关（type punning）。那在 C 里是常见技巧，
//      但在 C++ 里是未定义行为，编译器优化后可能给你意外结果。
//
//   3. 这个函数只回答"现在跑的这台机器是什么端序"，它**不能**用来解析协议。
//      协议端序是写死在规范里的，不管你跑在哪台机器上都必须按规范来。
//      这就是第 2 题存在的理由。
//
// ===========================================================================
bool is_little_endian() {
    const std::uint16_t probe=1u;
    const std::uint8_t *p=reinterpret_cast<const std::uint8_t*>(&probe);
    return *p==1u;
}

// ===========================================================================
// 第 4 题 · find_byte —— 在内存区间里找一个字节
// ===========================================================================
//
// 【含义】
//   在 [first, last) 这个半开区间里查找等于 value 的字节。
//   找到就返回指向它的指针，没找到返回 nullptr。
//
//   注意 last 是开区间：它指向的那个元素**不参与**查找。
//     find_byte(data, data + 6, x)   检查的是 data[0] 到 data[5]
//
// 【场景】
//   串口收到一帧数据放在缓冲区里，你要找帧头 0xAA 在哪里；
//   或者在一段 DMA 缓冲区里搜某个分隔符。这是解析协议的第一步。
//
// 【思路】
//   直接用指针做循环变量，这是 C++ 标准库的写法。伪代码：
//
//     让 p 从 first 出发
//     只要 p 不等于 last，就看 *p 是不是 value，是就返回 p
//     然后 p 往后走一格
//     循环结束说明没找到，返回 nullptr
//
//   注意 ++p 是"往后走一个字节"，不是"地址加 1"。
//   指针的加减以**元素大小**为单位，只不过这里元素正好是 uint8_t。
//
// 【陷阱】
//   1. 为什么用"起止指针"而不是"起始指针 + 长度"？
//      因为指针比较天然严谨：如果长度算错了，你可能越界读；
//      而 p != last 这个条件不依赖任何算术，空区间（first == last）时
//      循环体一次都不进，天然安全。
//
//   2. 一定要返回**第一个**匹配项。测试里 {1,2,1,3} 找 1 必须返回
//      下标 0 而不是 2。
//
//   3. 没找到返回 nullptr，不要返回 last。虽然两者都能表达"没找到"，
//      但接口约定是 nullptr，调用方会照这个写判断。
//
// 【写完自检】
//   测试会检查：正常找到、找第一个而不是最后一个、找不到、空区间、
//   以及"last 指向的元素取不到"（验半开区间的语义）。
//
// ===========================================================================
const std::uint8_t* find_byte(const std::uint8_t* first,
                              const std::uint8_t* last,
                              std::uint8_t value) {
    for(const std::uint8_t *p=first;p!=last;++p)
{
    if(*p==value)
    {
        return p;
    }
}
return nullptr;
}

// ===========================================================================
// 第 5 题 · reg_set_bits / reg_clear_bits / reg_toggle_bits
//            —— 寄存器位操作，也就是 volatile 的正确用法
// ===========================================================================
//
// 【含义】
//   这三个函数直接操作"硬件寄存器"：
//     reg_set_bits(reg, mask)      把 mask 里为 1 的位都置成 1
//     reg_clear_bits(reg, mask)    把 mask 里为 1 的位都清成 0
//     reg_toggle_bits(reg, mask)   把 mask 里为 1 的位翻转
//   三种操作都只影响 mask 圈出来的那些位，其它位保持不变。
//
//   注意参数类型是 volatile std::uint32_t*，这是本课的重点。
//
// 【场景】
//   这就是你写 MCU 驱动时每天都在做的事。比如点亮板子上的 LED：
//     reg_set_bits(&GPIOA_ODR, 1u << 5);     // PA5 输出高电平
//     reg_clear_bits(&GPIOA_ODR, 1u << 5);   // PA5 输出低电平
//
// 【volatile 到底在干什么】
//   假设你写了一个"等待硬件就绪"的循环：
//     while ((*status_reg & READY) == 0) { }
//   如果 status_reg 不是 volatile 的，编译器会这样想：
//   "循环体里没人修改这个值，那我何必每次重新读？读一次存到寄存器里，
//    然后在这个缓存值上循环就行了。" 于是变成死循环。
//
//   但寄存器是被**硬件**改的，编译器看不见这件事。volatile 就是在告诉它：
//   "这块内存可能被程序之外的东西改变，每一次读写都必须真的发生，
//    不许缓存、不许合并、不许删除。"
//
// 【思路】
//   就是最朴素的三种位运算，没什么技巧：
//     置位： *reg |= mask;
//     清位： *reg &= ~mask;
//     翻转： *reg ^= mask;
//
//   看起来像"读-改-写"三步，但对 volatile 指针，编译器保证这三步会
//   老老实实生成读、改、写的指令，不会被优化掉或合并。
//
// 【陷阱】
//   1. 参数为什么必须是 volatile 指针？
//      如果签名写成 uint32_t*，调用方就得 const_cast 强行丢掉 volatile 限定，
//      那等于明确告诉编译器"请随便优化我的硬件访问"，灾难。
//      用 volatile 指针当参数，编译期就挡住了这种错误用法。
//
//   2. volatile **不等于**线程安全，也**不等于**原子操作。
//      它只保证"访问真的发生了"，不保证原子性、不保证顺序、不保证
//      多核之间的可见性。做中断和并发要用 std::atomic，第 08 课专门讲。
//
//   3. 真实项目里读-改-写还有个更隐蔽的坑：**读和写之间可能被中断打断**，
//      另一个上下文改的那些位会被你写回去的值覆盖掉。这叫
//      read-modify-write race。第 08 课会给出解决方案。现在先按最简单的写。
//
// 【写完自检】
//   测试会验证三种操作各自正确，还会特别检查清位时"没圈到的位没被动过"。
//
// ===========================================================================
void reg_set_bits(volatile std::uint32_t* reg, std::uint32_t mask) {
    *reg|=mask;
}

void reg_clear_bits(volatile std::uint32_t* reg, std::uint32_t mask) {
    *reg&=!mask;
}

void reg_toggle_bits(volatile std::uint32_t* reg, std::uint32_t mask) {
    *reg^=mask;
}

// ===========================================================================
// 第 6 题 · pack_frame / unpack_frame —— 内存布局 vs 协议布局
// ===========================================================================
//
// 【含义】
//   结构体 SensorFrame 是数据在**内存里**的样子，成员顺序是按可读性定的：
//     id (2字节) + temperature_q8 (2字节) + timestamp_ms (4字节) + crc (1字节)
//
//   但这份数据在**协议线上**的样子是另一回事，规范规定得很死：
//     偏移 0..1 : id             uint16，小端
//     偏移 2..3 : temperature    int16， 小端
//     偏移 4..7 : timestamp_ms   uint32，小端
//     偏移 8    : crc            uint8
//   一共 9 个字节，紧凑排列，没有空隙。
//
//   pack_frame 负责把内存里的结构体"打包"成这 9 个字节。
//   unpack_frame 负责反方向：从这 9 个字节还原出结构体。
//
// 【场景】
//   这是嵌入式通讯的心脏。传感器通过 UART/CAN/BLE 把数据发给主控，
//   两边必须对字节的排列方式有完全一致的理解，否则收到的就是垃圾。
//
// 【为什么不能直接把结构体扔出去】
//   你可能会想：直接 send(&frame, sizeof(frame)) 不就行了？
//   不行，至少有三个问题：
//
//   1. sizeof(SensorFrame) 是 12，不是 9！
//      因为编译器会在成员之间插入**填充字节**（padding），让每个成员
//      都落在自己需要的对齐位置上。多出来的 3 个字节对方不认识。
//      测试里专门断言了 sizeof(SensorFrame) == 12 和
//      offsetof(SensorFrame, crc) == 8，你可以对照着看布局。
//
//   2. 填充字节的**内容是不确定的**。可能是栈上残留的旧数据，
//      直接发出去等于泄露内存内容。
//
//   3. 端序还没处理。内存里的字节顺序取决于 CPU，协议要求的是小端。
//
//   所以必须显式地一个字段一个字段地序列化。多写十几行代码，
//   换来确定的、可移植的、可测试的行为 —— 这是嵌入式协议处理的铁律。
//
// 【思路】pack_frame
//   先检查容量：如果 cap 小于 9，直接返回 0，**而且一个字节都不能写**。
//   （为什么？半途失败会留下半个包，比什么都不写更糟 —— 发送方可能
//     以为打包成功了。）这是"要么全做，要么不做"的接口设计。
//
//   然后按偏移量逐字段写：
//     偏移 0 写 id（2 字节小端）
//     偏移 2 写 temperature_q8（2 字节小端）
//     偏移 4 写 timestamp_ms（4 字节小端，可以复用第 2 题的 write_u32_le）
//     偏移 8 写 crc（1 字节，直接赋值就行）
//   注意 temperature_q8 是 int16_t，写之前要先转成 uint16_t 的位模式：
//     static_cast<std::uint16_t>(f.temperature_q8)
//   负数的转换是良定义的（按 2^16 取模），得到的正是它的补码表示。
//
// 【思路】unpack_frame
//   先检查长度：len < 9 就返回 false。
//   然后按同样的偏移量逐字段读回来。16 位和 32 位的读取都可以自己写
//   小端拼装，或者复用第 2 题的 read_u32_le。
//
// 【陷阱】
//   1. 绝对不能写 *reinterpret_cast<std::uint16_t*>(in + 2)。
//      in 指向的是一个字节缓冲区，不保证对齐 —— 在 Cortex-M0 上这会
//      直接触发 HardFault。必须逐字节拼。
//
//   2. 容量/长度检查要在最前面，而且在写任何东西之前。
//      测试会给你一个 8 字节的缓冲区，然后检查里面原来的内容**一点没变**。
//
//   3. 写完记得数一数是不是正好 9 字节。多写或少写一个字节，
//      对方解析时就会错位，而且错误会一路蔓延到后面的所有字段。
//
// 【写完自检】
//   测试会用一个具体的数据（id=0x1234, 温度=-10.0°C, 时间戳=0xABCD,
//   crc=0x5A）逐字节核对打包结果，然后再反序列化回来对比是否一致。
//
// ===========================================================================
std::size_t pack_frame(const SensorFrame& f, std::uint8_t* out, std::size_t cap) {
   if(out==nullptr|cap<kFrameWireSize){
    return 0;
   }
   put_u16_le(out+0,f.id);
   put_u16_le(out+2,static_cast<std::uint16_t>(f.temperature_q8));
   write_u32_le(out+4,f.timestamp_ms);
   put_u16_le(out+8,f.crc);
    return kFrameWireSize;
}  // namespace lab02

bool unpack_frame(const std::uint8_t* in, std::size_t len, SensorFrame* out) {
    if (in == nullptr || out == nullptr || len < kFrameWireSize) {
        return false;
    }

    out->id             = get_u16_le(in + 0);
    out->temperature_q8 = static_cast<std::int16_t>(get_u16_le(in + 2));
    out->timestamp_ms   = read_u32_le(in + 4);
    out->crc            = in[8];

    return true;
}

