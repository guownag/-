// 第 2 题 · RAII 片选
// ===========================================================================
//
// 【含义】
//   SPI 通信的规矩：和某个器件说话之前先把它的片选（CS, Chip Select）
//   引脚拉低，说完话再拉高。一次通信必须完整地"拉低 -> 收发 -> 拉高"。
//
//   ChipSelect 干的就是这件事：
//     构造：拉低片选，hw().cs_active = true
//     析构：拉高片选，hw().cs_active = false
//
// 【场景】
//   SPI 总线上通常挂着好几个器件（Flash、屏幕、传感器），
//   它们共用时钟和数据线，靠片选决定"现在跟谁说话"。
//
//   如果片选没拉高就离开，会有两个后果：
//     1. 这个器件一直以为你在跟它说话，收到一堆垃圾数据
//     2. 别的器件说的话它也在听，可能误动作（比如误写 Flash）
//
//   用 RAII 包起来，**通信结束片选一定会释放**，哪怕中间出了错、
//   提前返回、或者代码写错了。
//
// 【思路】
//   构造函数：
//       ++hw().cs_low_calls;
//       hw().cs_active = true;
//
//   析构函数：
//       ++hw().cs_high_calls;
//       hw().cs_active = false;
//
//   就这么简单。**简单正是它好用的原因。**
//
// 【陷阱】
//   1. 真正的 SPI 收发代码应该写在片选有效的这段作用域**里面**：
//          {
//              ChipSelect cs;
//              spi_transfer(0x9F);        // 读器件 ID
//              id = spi_transfer(0x00);
//          }                              // 这里片选自动释放
//      写在花括号外面就白搭了。
//
//   2. 同样禁止拷贝 —— 两个对象析构两次会把片选拉高两次，
//      如果此时另一个器件正被选中，就会被误释放。
//
//   3. 真实硬件上"拉低/拉高"是写 GPIO 寄存器（第 02 课那套），
//      这里用计数器模拟，道理完全一样。
//
