// 第 4 题 · 滑动平均滤波器
// ===========================================================================
//
// 【含义】
//   MovingAverage 保留最近 window 个采样值，value() 返回它们的平均值。
//   新样本进来时，如果缓冲已满，最老的那个被挤出去。
//
//      MovingAverage avg(4);
//      avg.push(10);   // 平均 = 10
//      avg.push(20);   // 平均 = (10+20)/2 = 15
//      avg.push(30);   // 平均 = 20
//      avg.push(40);   // 平均 = 25
//      avg.push(50);   // 10 被挤掉，平均 = (20+30+40+50)/4 = 35
//
// 【场景】
//   ADC 采样总有噪声，直接拿去做控制会让执行机构抖个不停。
//   最简单有效的办法就是滑动平均 —— 它是个低通滤波器，
//   能把高频噪声压下去，代价是响应变慢。
//
//   温度、电压、电流采样几乎都会先过一遍这个。
//
// 【思路】内部用环形缓冲
//   一个固定大小数组，加一个写指针，写到末尾就绕回开头。
//   这样不用搬移数据，也不用动态分配。五个成员变量：
//     m_buf[kMaxWindow]  存样本的数组
//     m_sum              当前所有有效样本的和   ← 关键优化
//     m_window           实际窗口大小（1..kMaxWindow）
//     m_count            已经收了多少个（最多 m_window）
//     m_index            下一个要写的位置
//
//   为什么要维护 m_sum？否则每次求平均都要遍历一遍数组，O(window)。
//   维护一个 running sum 之后 push 和 value 都是 O(1)，
//   这在 1kHz 的控制循环里差别很大。
//
//   构造函数用成员初始化列表（冒号后面那一串）初始化所有成员。
//   注意 window 要先用函数体钳到 [1, kMaxWindow]，再赋给 m_window。
//
//   push 的逻辑：
//       缓冲还没满（m_count < m_window）：
//           写进 m_buf[m_index]，m_sum 加上它，++m_count
//       已经满了：
//           m_sum 先减掉要被覆盖的那个旧值，再写入新值并加到 m_sum
//       最后 m_index 往前挪一格，到末尾就绕回 0：
//           m_index = (m_index + 1) % m_window;
//
//   value()：m_count == 0 时返回 0，否则 return m_sum / m_count。
//   count() 和 window() 直接返回对应的成员。
//
// 【陷阱】
//   1. 别忘了减掉被挤出去的旧值。如果只在满了之后 m_sum += sample，
//      和会一直涨，平均值就完全错了。测试里连续 5 个样本那段专抓这个。
//
//   2. value() 要处理 m_count == 0 的情况 —— 除以 0 是未定义行为。
//
//   3. 三个只读函数必须标 const（头文件里已经写了）。不标的话
//      在 const 对象或 const 引用上就调不了。
//
//   4. m_sum 是 int32_t，窗口很大且样本也大时会溢出。真实项目里要么
//      限制样本范围，要么用 int64_t 存和。这里为了简单用 int32_t。
//
//   5. 取平均值是整数除法，会向下取整。嵌入式里本来也尽量避免浮点。
//
// ===========================================================================
