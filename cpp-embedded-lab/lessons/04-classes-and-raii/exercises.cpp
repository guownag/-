// 第 1 题 · RAII 临界区
// ===========================================================================
//
// 【含义】
//   RAII = Resource Acquisition Is Initialization（资源获取即初始化）。
//
//   名字很拗口，但想法极简单：
//     **构造函数负责获取资源，析构函数负责释放资源。**
//
//   于是你只要创建一个对象，资源就自动被管住了；对象离开作用域时，
//   析构函数一定会被调用，资源自动归还。**你不需要记得写释放代码。**
//
//   这一题要做的 CriticalSection 是最经典的例子：
//     - 构造函数：关中断，++nesting
//     - 析构函数：--nesting，如果是 0 就开中断
//
// 【场景】
//   嵌入式里到处是"配对操作"：关中断/开中断、拉低片选/拉高、
//   上锁/解锁、打开时钟/关闭时钟。手写配对代码的问题是：
//
//      disable_irq();
//      if (error) {
//          return;              // ← 忘了开中断！中断从此永远关着
//      }
//      do_something();
//      enable_irq();
//
//   只要有**一条**提前返回或者 break，配对就断了。而且这种 bug
//   往往只有在错误路径上才出现，测试根本测不到。
//
//   用 RAII 就永远不会忘：
//
//      {
//          CriticalSection cs;        // 自动关中断
//          if (error) { return; }     // 提前返回也没关系
//          do_something();
//      }                              // 无论怎么离开作用域，都会开中断
//
//   **这是 C++ 在嵌入式里最有价值的特性之一。**用好了能消灭一整类 bug。
//
// 【思路】
//   构造函数：
//       if (hw().irq_nesting == 0) { ++hw().irq_disable_calls; }
//       ++hw().irq_nesting;
//
//   析构函数：
//       --hw().irq_nesting;
//       if (hw().irq_nesting == 0) { ++hw().irq_enable_calls; }
//
//   为什么要判断 nesting == 0？因为**嵌套**。看这个场景：
//
//       CriticalSection outer;      // 关中断，nesting 0 -> 1
//       CriticalSection inner;      // 已经关着了，不用再关，nesting 1 -> 2
//       ...
//       // inner 析构：nesting 2 -> 1，还不到 0，**不能开中断**
//       // outer 析构：nesting 1 -> 0，现在才真的开中断
//
//   如果在构造/析构里无条件地开关，内层析构就会提前把中断打开，
//   外层保护的代码段就裸奔了 —— 而且这种 bug 只在嵌套时出现，极难查。
//
// 【陷阱】
//   1. **析构函数里不要抛异常**（虽然本工程禁用了异常，但这是通用规矩）。
//      析构函数在栈展开时被调用，再抛异常会让程序直接终止。
//
//   2. **禁止拷贝**。头文件里已经用 `= delete` 写好了：
//          CriticalSection(const CriticalSection&) = delete;
//      如果不禁止，拷贝出来的对象析构时也会去开中断，计数就乱了。
//      `= delete` 让这种错误在**编译期**就被挡住。
//
//   3. 别把 `CriticalSection` 对象存起来当成员变量长期持有 ——
//      RAII 的对象应该活在**尽可能小的作用域**里，用完即走。
//
// 【写完自检】
//   测试会验证：进入作用域时 nesting 变 1、离开时变 0；
//   嵌套时只在最外层真的开关；disable/enable 的调用次数正确。
//
