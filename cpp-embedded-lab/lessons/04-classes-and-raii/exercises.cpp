// 第 3 题 · 生命周期计数器
// ===========================================================================
//
// 【含义】
//   这个类的唯一目的是让你**看见**编译器什么时候悄悄调用了构造函数、
//   拷贝构造函数和析构函数。
//
//   四个静态计数器各自的含义（头文件里也有）：
//     alive        当前活着的对象数
//     constructed  默认构造次数
//     copied       拷贝构造 + 拷贝赋值次数
//     destroyed    析构次数
//
// 【场景】
//   嵌入式最怕的就是"不知不觉多了一次拷贝"。比如一个 256 字节的结构体
//   在函数返回时被拷贝，占了 256 字节的栈。多来几次栈就爆了，
//   而爆栈的表现是"程序随机跑飞"，几乎没法调试。
//
//   学会数清楚"这里到底拷贝了几次"，是控制资源的第一步。
//
// 【思路】四个函数各管一件事
//   默认构造：   ++constructed; ++alive;
//   拷贝构造：   ++copied;      ++alive;      （新对象诞生了）
//   拷贝赋值：   ++copied;                     （没有新对象，alive 不变！）
//   析构：       ++destroyed;   --alive;
//
//   注意拷贝赋值和拷贝构造的区别：
//     拷贝构造  = 造一个新对象，用另一个对象初始化它   -> alive 加一
//     拷贝赋值  = 两个对象都已经存在，把右边的值抄给左边 -> alive 不变
//
//   这个区别是理解 Rule of 3 的关键。
//
//   reset_stats() 把四个计数器全清零。
//
// 【陷阱】
//   1. 拷贝构造的参数必须是 `const LifetimeCounter&`（引用），
//      **不能是值传递**。如果是值传递，传参的时候又要拷贝一次，
//      就会无限递归下去。这是 C++ 里最经典的错误之一。
//
//   2. 拷贝赋值要返回 `LifetimeCounter&`（自己的引用），
//      这样才能支持 `a = b = c` 这种链式赋值。本课的实现体里
//      只要 `return *this;` 就行。
//
//   3. 赋值运算符里本可以检查"自己给自己赋值"（`if (this == &other)`），
//      这个类没有真实资源，不检查也没关系。第 05 课讲 Rule of 3 时
//      会看到需要检查的版本。
//
//   4. `reset_stats()` 把四个计数器全部清零。它只应该在确实没有存活
//      对象的时候调用，否则 alive 的数字会变成假的。测试就是这么用的。
//
// 【写完自检】
//   测试会创建几个对象，观察四个计数器怎么变，
//   并验证"离开作用域后 alive 回到 0"。
//
// ===========================================================================
