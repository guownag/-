// 第 5 题 · array_max —— constexpr 遍历数组
// ===========================================================================
//
// 【含义】
//   返回数组里最大的元素。同样做成 `constexpr`，
//   所以它既能在编译期算，也能在运行时算。
//
// 【场景】
//   找最大值在嵌入式里到处用：ADC 采样峰值、电池电压最高点、
//   通信超时最长的那一帧。
//
//   而"编译期找最大值"的用途是：**检查常量表的内容合不合理**。
//   比如一张增益表，你可以用 static_assert 保证它的最大值不超过
//   某个安全上限，改表的时候一旦越界，编译直接失败。
//
// 【思路】
//   先假设第一个元素最大，然后从下标 1 开始逐个比较：
//
//      T best = data[0];
//      for (std::size_t i = 1u; i < N; ++i) {
//          if (data[i] > best) { best = data[i]; }
//      }
//      return best;
//
//   和第三课的 min_max 是同一个套路，只是这里只求最大值，
//   而且要求能编译期求值。
//
// 【陷阱】
//   1. 和 array_count 一样，参数要用 `const T (&data)[N]`（引用），
//      否则数组会退化成指针，N 推不出来。
//
//   2. **要从下标 1 开始，不能用下标 0 和 best 比。**
//      用 data[0] 初始化 best 之后，第一轮就该比 data[1]。
//      从 0 开始也没错，但多一次无意义的比较。
//
//   3. 不能用 0 或者某个"极小值"当初始值。数组里全是负数的时候就错了。
//      **用 data[0] 初始化永远正确**（这是第三课已经讲过的坑）。
//
//   4. constexpr 函数里用循环需要 C++14 以上，本工程是 C++17，没问题。
//
// 【做完之后，体验编译期求值】
//   把下面两行的注释去掉，编译一次：
//
// constexpr std::int32_t kProbe[4] = {3, 9, -2, 7};
// static_assert(array_max(kProbe) == 9, "array_max 在编译期算错了");
//
//   如果通过，说明 array_max 真的在编译期跑完了 —— 运行时一个指令都不花。
//
// ===========================================================================
template <typename T, std::size_t N>
constexpr T array_max(const T (&data)[N]) {
    (void)data;
    // TODO
    return data[0];
}

