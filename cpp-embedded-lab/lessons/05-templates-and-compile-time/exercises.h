// ===========================================================================
// 第 4 题 · FixedVector<T, N> —— 类模板
// ===========================================================================
//
// 【含义】
//   一个固定容量的"动态数组"：容量 N 在编译期就定死，元素类型是 T。
//
//      FixedVector<std::int32_t, 8> v;   // 最多装 8 个 int32_t
//      v.push_back(42);
//      v[0]           // 42
//      v.size()       // 1
//      v.capacity()   // 8
//
//   **它和 std::vector 的区别是：容量固定，从不分配内存。**
//   所有存储都在对象自己身上（一个 `std::array<T, N>` 成员）。
//
// 【场景】
//   这是嵌入式里最该用的"容器"。原因很简单：
//
//     std::vector 会在运行时向堆要内存。堆碎片、分配失败、
//     分配耗时不确定 —— 这三件事在跑几个月的设备上都是灾难。
//
//   FixedVector 的容量是编译期常量，对象多大在编译期就确定了，
//   进来多少字节的 RAM、什么时候用完，全都算得出来。
//   **这是嵌入式最看重的"确定性"。**
//
//   第 06 课会把它扩展成更完整的版本（带迭代器、insert 等）。
//
// 【思路】逐个实现，都很短
//   构造函数：把 m_size 设成 0，m_data 清零
//     FixedVector() : m_data{}, m_size(0u) {}
//
//   size() / capacity() / empty() / full()：一行一个
//     capacity() 直接返回 N（它是模板参数，编译期就知道）
//
//   push_back(v)：
//     满了（m_size >= N）就返回 false，不要覆盖已有数据
//     否则 m_data[m_size] = v; ++m_size; return true;
//
//   clear()：m_size = 0 就行。
//     **不需要清空数组内容** —— m_size 是唯一的事实来源，
//     超过 m_size 的位置不会被读到（和第三课的 event_reset 一个道理）。
//
//   operator[] 两个版本：
//     非 const 版本返回 T&，可以写 v[0] = 5;
//     const 版本返回 const T&，用于只读访问
//     **两个都要写**，否则 const 对象就索引不了。
//
// 【陷阱】
//   1. `static_assert(N > 0, ...)` 那一行已经给你了。它保证容量不能是 0 ——
//      否则 `m_data` 就是空数组，一切都没意义。这是"把假设写成代码"。
//
//   2. `operator[]` **不做越界检查**，这是刻意的（和第 01 课的 extract_field
//      一样，属于"调用方保证前提"的接口）。越界访问是调用方的责任。
//      真实项目里可以加断言，但不能改变返回值类型。
//
//   3. 两个 operator[] 的区别只在 const 上，写法容易抄错。
//      记住：const 成员函数里的 this 是 const 的，所以只能返回 const T&。
//
//   4. 类模板的所有成员函数也都要写在头文件里（或者用 `inline` 定义
//      在头文件里），原因和普通模板一样。
//
// ===========================================================================
