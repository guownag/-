namespace lab05 {

// 【已提供】把低 8 位截出来。
//
// 这种"参数类型固定"的函数，编译器不需要看到定义就能生成调用代码 ——
// 它只要知道函数长什么样（声明）就够了，具体实现在链接阶段再找。
//
// 模板就不一样了：编译器在调用点必须看到完整定义，才能生成具体类型的
// 代码。这就是模板必须写在头文件里的全部原因。
std::uint32_t truncate_to_u8(std::uint32_t value) {
    return value & 0xFFu;
}

}  // namespace lab05
