// ===========================================================================
// 第 2 题 · insert_field / extract_field —— 读写寄存器里的"字段"
// ===========================================================================
//
// 【含义】
//   一个 32 位寄存器不是"一个数"，而是被切成了好几段，每段有各自的含义：
//
//     bit 31        ...        8  7    4  3    2  1  0
//     +--------------------------+------+------+------+
//     |       保留/其他功能       | 字段B | 字段A | 使能 |
//     +--------------------------+------+------+------+
//                                   ^
//                          从 bit 4 开始，宽 4 位
//
//   extract_field(reg, lsb, width)：把这一段抠出来，移到最低位，高位补 0。
//     相当于"读这个字段现在是什么值"。
//
//   insert_field(reg, lsb, width, value)：把这一段替换成 value，
//     其它所有位一个都不能动。相当于"改这个字段的配置"。
//
// 【场景】
//   驱动开发里这两个函数会被调用几百次。比如配置 UART：
//     insert_field(UART_CR, 4, 4, 3);   // bit 7:4 设成 3，选波特率
//   关键是"其它位不能动" —— 你可能已经在这个寄存器里配好了中断使能、
//   校验位等等，随手改一下就把别人的配置抹掉了。
//
// 【思路】insert 分三步
//   第 1 步：造出目标字段的掩码。字段宽 width 位、从 lsb 开始，
//           所以掩码是 make_mask(width) << lsb。
//   第 2 步：把 reg 里属于这个字段的位清零，其它位保留：
//           reg &= ~fieldMask
//   第 3 步：把 value 放进这些位置：
//           reg |= (value << lsb) & fieldMask
//           那个 & fieldMask 是关键 —— value 的高位必须被切掉，
//           不然它会串进旁边那个字段里。
//
// 【思路】extract 只有一步
//   先右移到最低位，再掩码：(reg >> lsb) & make_mask(width)
//   两个动作缺一不可：右移负责"把字段挪到低位"，掩码负责"把上面残留的
//   位切掉"。少任何一个都会拿到错的答案，等下的图解会看到为什么。
//   （也可以写成 ((reg & (make_mask(width) << lsb)) >> lsb)，同样正确，
//     但多一次移位，没必要。）
//
// 【陷阱】
//   1. 忘了 & fieldMask：value = 0xFF 写进一个 4 位字段，
//      会把上面 4 位也改掉。测试专门检查这种越界。
//   2. width == 32 的情况交给 make_mask 处理，别自己再重写一遍边界判断。
//   3. 别硬编码 0xFF、0xF 这种 magic number，一律用 make_mask 算出来。
//
// 【写完自检】
//   测试会检查"改了目标字段之后其它位一点没变"，
//   还会检查 insert 和 extract 互为逆运算。
//
// ===========================================================================
std::uint32_t insert_field(std::uint32_t reg, unsigned lsb, unsigned width, std::uint32_t value) {
    (void)reg; (void)lsb; (void)width; (void)value;
    std::uint32_t field_mask=make_mask(width);
    reg&=~(field_mask<<lsb);
    reg|=(value<<lsb)&(field_mask<<lsb);
    return reg;
}

std::uint32_t extract_field(std::uint32_t reg, unsigned lsb, unsigned width) {
    std::uint32_t field_mask=make_mask(width);
    return (reg>>lsb)&field_mask;
}

// ===========================================================================
// 第 3 题 · popcount32 —— 数一个数里有几个 1
// ===========================================================================
//
// 【含义】
//   把 v 写成二进制，数一数有几个 1。
//
//     popcount32(0x00000000) = 0
//     popcount32(0x0000000F) = 4
//     popcount32(0x80000001) = 2
//     popcount32(0xFFFFFFFF) = 32
//
//   名字来自 population count，中文叫"汉明重量"。有些 ARM 芯片
//   甚至有一条指令直接算它。
//
// 【场景】
//   * 中断标志寄存器一次挂起好几个中断源，你要知道有几个在等，
//     或者找出编号最小的那个（决定谁先被服务）。
//   * CRC 校验、位图分配器、触摸按键多点检测，底层都是它。
//
// 【思路】
//   按位遍历 32 次当然能写对，但有个更漂亮的技巧：
//
//     v &= (v - 1)
//
//   这一句恰好能消掉最低位的那个 1，高位全部保留。拿数字验一下：
//
//     v         = 0b1100  (12)
//     v - 1     = 0b1011  (11)
//     v & (v-1) = 0b1000  (8)    <- 最右边那个 1 没了
//
//   所以循环到 v 变成 0 为止，循环了几次就有几个 1。
//   好处：循环次数等于 1 的个数，而不是固定 32 次。
//   MCU 上省下来的周期就是省下来的电。
//
// 【陷阱】
//   别用编译器内置函数（MSVC 的 __popcnt、GCC 的 __builtin_popcount），
//   也别查表。理由：不是所有 MCU 都有这条指令，你要会写不依赖它的版本。
//   以后在性能敏感的场合再用内置函数，但前提是先能写出正确版本。
//
// 【写完自检】
//   测试有 7 条，其中全 1 那条期望值是 32，能验出循环边界有没有写错。
//
// ===========================================================================
unsigned popcount32(std::uint32_t v) {
    unsigned count = 0;
    while (v != 0u) {
        v &= (v - 1u);
        ++count;
    }
    return count;
}

// ===========================================================================
// 第 4 题 · clamp_i32 —— 钳位
// ===========================================================================
//
// 【含义】
//   把 v 限制在 [lo, hi] 区间内，两个端点算在里面（闭区间）。
//
//     clamp_i32(5,   0, 10) = 5      在范围内，原样返回
//     clamp_i32(-5,  0, 10) = 0      太小，顶到下界
//     clamp_i32(50,  0, 10) = 10     太大，顶到上界
//     clamp_i32(10,  0, 10) = 10     正好在端点上，仍然是 10
//
// 【场景】
//   这是"防呆"的通用工具。PID 控制器的输出要限幅（不然电机直接满速），
//   ADC 采样值要防越界（传感器坏了可能返回离谱的值），
//   PWM 占空比写进寄存器之前要确认在 0~100% 之间。
//
//   为什么不在写寄存器的时候判断？因为一个值可能经过好几层计算，
//   在最外层钳住它，比在每一层都判断要清楚得多。
//
// 【思路】
//   两句话：比下界小就返回下界，比上界大就返回上界，都不是就返回原值。
//
// 【陷阱】
//   端点必须包含在内，所以判断用 < 和 >，不能用 <= 和 >=。
//   测试里专门有 clamp_i32(0,0,10) 和 clamp_i32(10,0,10) 两条盯着你。
//
//   另外：这一题只处理 32 位有符号整数。真项目里如果调用方把 lo、hi 传反了
//   （比如 clamp_i32(x, 10, 0)），函数不会有任何抱怨，只是返回垃圾值。
//   这是调用方的责任，接口层面通常用断言挡住（第 12 课讲）。
//
// ===========================================================================
std::int32_t clamp_i32(std::int32_t v, std::int32_t lo, std::int32_t hi) {
    if(v<lo)
    {
        return lo;
    }
    else if(v>hi)
    {
        return hi;
    }
    else
    {
        return v;
    }
}

// ===========================================================================
// 第 5 题 · sat_add_i16 —— 饱和加法
// ===========================================================================
//
// 【含义】
//   算 a + b，但如果结果超出 int16_t 的表示范围（-32768 ~ 32767），
//   不要让它绕回去，而是**停在边界上**。
//
//     100 + 200      = 300        正常
//     32767 + 1      = 32767      本该是 32768，顶住上界
//     -32768 + -1    = -32768     本该是 -32769，顶住下界
//     -32768 + 32767 = -1         恰好不溢出，正常返回
//
//   "停在边界"这个行为叫**饱和**(saturation)，相反的行为叫**回绕**
//   (wrap-around)。默认的整数加法是回绕的：32767 + 1 会变成 -32768。
//   想象温度传感器读到 32767，加一度突然变成 -32768 度。
//
// 【场景】
//   最典型的例子是电机电流环的积分项。一次回绕，PWM 输出从 +100% 瞬间
//   跳到 -100%，电机会发出巨响甚至烧驱动。饱和最坏是持续顶在上限，
//   控制器还能慢慢收敛回来。
//
//   所以嵌入式里只要运算结果会流向硬件，基本都要做饱和版本。
//
// 【思路】
//   关键一步：**先把两个 int16_t 提升到 int32_t 再相加。**
//   int32_t 的范围足够装下任何两个 int16_t 的和，这一步永远不会溢出。
//   然后在 int32_t 的世界里比较，最后再转回 int16_t。
//
//     int16_t a, b;                             // -32768 ~ 32767
//     int32_t sum = (int32_t)a + (int32_t)b;    // -65536 ~ 65534，安全
//     然后 sum > 32767 就返回 32767，sum < -32768 就返回 -32768
//
// 【陷阱】
//   为什么不能直接写 if (a + b > 32767) ？
//   a 和 b 是 int16_t，相加时会被**整型提升**成 int 再算。在 32 位平台上
//   int 就是 32 位，a + b 不会溢出，这个判断居然是对的 —— 于是代码看着
//   没问题、测试也过了。但换到 int 只有 16 位的平台（很多 8/16 位 MCU），
//   a + b 自己就溢出了，判断完全失去意义。
//
//   "在 A 平台能跑、换 B 平台就崩"是嵌入式最怕的 bug 类型。
//   显式用 int32_t 做中间计算，就把这条路彻底堵死了。
//
// 【写完自检】
//   测试有 8 条，覆盖上溢、下溢、刚好不溢出。
//   特别看 sat_add_i16(-32768, 32767) 是不是 -1 —— 这条测的是
//   "别把不该钳的也钳了"。
//
// ===========================================================================
std::int16_t sat_add_i16(std::int16_t a, std::int16_t b) {
    std::int32_t sum=(std::int32_t)a+(std::int32_t)b;
    if(sum>32767)
    {
        return 32767;
    }
    else if(sum<-32768)
    {
        return -32768;
    }
    else
    {
        return static_cast<std::int16_t>(sum);
    }
}

// ===========================================================================
// 第 6 题 · q15_mul —— Q15 定点乘法
// ===========================================================================
//
// 【含义】
//   Q15 是一种"用整数假装小数"的编码方式，约定是：
//
//     实际值 = 存储值 / 32768
//
//   于是 16 位整数被赋予了新的含义：
//     存储值      0  ->  实际值  0.0
//     存储值  16384  ->  实际值  0.5
//     存储值  32767  ->  实际值  ≈ 0.99997   （最接近 1.0 的正数）
//     存储值 -32768  ->  实际值 -1.0          （只有 -1.0 是精确的）
//
//   为什么用 32768 而不是 10000？因为它正好是 2^15，
//   于是"除以 32768"可以用"右移 15 位"实现，在 MCU 上快得多。
//
//   本函数要算的是：两个 Q15 数相乘，结果仍然是 Q15 格式。
//
// 【场景】
//   为什么嵌入式不愿用 float？
//   1. 没有硬件 FPU 的 Cortex-M0/M3 上，一次浮点乘法要几十到上百个周期，
//      而且会悄悄链接进一个浮点运算库，固件体积多几 KB。
//   2. 浮点运算的耗时不确定，对硬实时的中断服务程序是灾难 ——
//      你没法保证它在截止时间前算完。
//
//   所以音频处理、电机控制、数字滤波里大量使用定点数。Q15 是最常用的格式。
//
// 【思路】
//   先把数学写清楚。设两个 Q15 数的存储值为 a、b，则：
//
//     实际值A = a / 32768
//     实际值B = b / 32768
//     乘积    = (a * b) / 32768 / 32768
//
//   我们要的结果也是 Q15 格式，也就是"实际值 × 32768"，所以：
//
//     结果存储值 = 乘积 × 32768 = (a * b) / 32768
//
//   也就是说：**只需要除一次 32768**，不是两次。用右移 15 位实现。
//
//   对应到代码是三步：
//     1. 用 int32_t 算 a * b       （见下面的陷阱，必须用 int32_t）
//     2. 加上 0x4000（半个 32768）做四舍五入
//     3. 算术右移 15 位
//
//   第 2 步为什么要加？因为整数除法会把小数部分丢掉。
//   0.25 × 32768 = 8192 恰好整除没问题，但 0.3 × 0.3 = 0.09，
//   0.09 × 32768 = 2949.12，直接截断得 2949；加半个 LSB 后得 2950，
//   更接近真实值。这就是"四舍五入"的标准做法：加一半，再向下取整。
//
// 【陷阱】
//   1. a * b 必须用 int32_t 装。32767 × 32767 约等于 2^30，
//      如果两边都是 int16_t，这个乘法在 32 位平台上会侥幸算对（整型提升），
//      换到 int 只有 16 位的平台就直接溢出。显式用 int32_t，别赌。
//
//   2. 右移负数在 C++17 里是"实现定义"的（标准没强制要求算术右移）。
//      好消息是 MSVC / GCC / Clang / IAR 都是算术右移，即向负无穷取整，
//      这正是我们想要的对称行为。
//
//   3. 别偷偷改成浮点版本 —— 那这一课就白上了。
//
// 【写完自检】
//   5 条测试里有正数、负数、乘 0、以及"接近 1.0 的平方"。
//   最有意思的是 q15_mul(32767, 32767) = 32766：
//   0.99997 的平方约等于 0.99994，乘 32768 得 32766 左右，
//   能验出你的四舍五入有没有生效。
//
// ===========================================================================
