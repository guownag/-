// ===========================================================================
// 第 6 题 · extern "C" —— 让 C 代码也能调用这个函数
// ===========================================================================
//
// 【含义】
//   C++ 会把函数名"改名"（name mangling），把参数类型编进符号里，
//   用来支持重载。C 不会。所以 C 代码链接不了 C++ 的函数。
//
//   extern "C" 就是告诉编译器："这个函数按 C 的规矩命名，不要改名。"
//
//   在 exercises.h 里的声明长这样：
//
//      #ifdef __cplusplus
//      extern "C" {
//      #endif
//
//      std::int32_t lab03_c_add(std::int32_t a, std::int32_t b);
//
//      #ifdef __cplusplus
//      }
//      #endif
//
//   `#ifdef __cplusplus` 是必需的：C 编译器不认识 extern "C" 这个关键字，
//   只有 C++ 编译器才需要看到它。这样同一个头文件 C 和 C++ 都能用。
//
// 【场景】
//   芯片厂家的 HAL 库、FreeRTOS、几乎所有嵌入式 SDK 都是 C 写的。
//   你要用 C++ 调用它们，或者把你的 C++ 模块暴露给 C 代码，
//   就必须处理这件事。这是 C++ 和 C 混编时的第一道关。
//
// 【思路】
//   实现的时候，函数定义也要带 extern "C"：
//
//      extern "C" std::int32_t lab03_c_add(std::int32_t a, std::int32_t b) {
//          return a + b;
//      }
//
//   （严格说，如果声明已经带了 extern "C"，定义时可以不重复写。
//     但显式写出来更清楚，尤其是这个定义单独出现在 .cpp 里的时候。）
//
// 【陷阱】
//   1. extern "C" 里不能有重载 —— C 没有重载的概念，两个同名函数
//      没办法区分。
//
//   2. extern "C" 影响的是【链接名】，不影响调用约定和参数传递规则。
//      参数类型还是要两边严格一致。
//
//   3. 头文件里的 extern "C" 要用 `#ifdef __cplusplus` 包起来，
//      否则 C 编译器会报语法错误。
//
